"""Generate agx3d_compose_corpus_vectors.c from in-tree inputs only.

  gen_agx3d_compose_corpus_vectors.py <out.c>

Every applegpu_g18g text in native/g18g (checked against manifest.json's
SHA-256) is split into its symbols, and each symbol into instructions with the
same first-match rule as the generated AGX3d disassembler
(src/asahi/isa/disasm-internal.h over src/asahi/isa/AGX3d.xml). Each
instruction is then decomposed into a field vector by the table-driven
decoder in ../agx3_compose/agx3_table.py over ../agx3_compose/agx3d_tables.c,
trying forms of the disassembler's mnemonic first. A decoded vector always
composes back to exactly the instruction's bytes.

These vectors are a round trip through one table: they prove that the C
composer, the Python decoder and Apple's bytes agree, but a field-to-bit
mapping that is wrong yet self-consistent would pass. What vouches for the
mapping is that the agx3d table comes from the same generator that
reproduces the independently produced agx3b and agx3c tables byte-exactly.
"""

import collections
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NATIVE = os.path.join(HERE, 'native', 'g18g')
TABLE = os.path.join(HERE, '..', 'agx3_compose', 'agx3d_tables.c')
ISA_DIR = os.path.join(HERE, '..', '..', 'isa')

sys.path.insert(0, os.path.join(HERE, '..', 'agx3_compose'))
sys.path.insert(0, ISA_DIR)
import agx3_table  # noqa: E402
from isa import load_isa  # noqa: E402


def segment(isa, data):
    """(offset, bytes, mnemonic) per instruction, as _disassemble_instr
    splits them; an unknown opcode is an error."""
    out = []
    i = 0
    while i < len(data):
        available = len(data) - i
        raw = int.from_bytes(data[i:i + 24], 'little')
        for instr in isa.instrs.values():
            n = instr.length[0]
            if (raw >> instr.length_bit) & 1:
                n = instr.length[-1]
            if n > available:
                continue
            masked = raw & ((1 << (8 * n)) - 1)
            if (masked & instr.exact.mask) == instr.exact.value:
                break
        else:
            sys.exit('unknown opcode at 0x%x' % i)
        out.append((i, bytes(data[i:i + n]), instr.display))
        i += n
    return out


def main():
    isa = load_isa(os.path.join(ISA_DIR, 'AGX3d.xml'))
    T = agx3_table.load(TABLE)
    D = agx3_table.Decoder(T)
    manifest = json.load(open(os.path.join(NATIVE, 'manifest.json')))['texts']

    seen = {}
    texts = set()
    decoded = 0
    for fn in sorted(manifest):
        m = manifest[fn]
        if m['arch'] != 'applegpu_g18g':
            continue
        data = open(os.path.join(NATIVE, fn), 'rb').read()
        assert hashlib.sha256(data).hexdigest() == m['sha256'], fn
        texts.add(fn)

        syms = sorted(m['symbols'].values())
        for start, end in zip(syms, syms[1:] + [m['size']]):
            for off, b, mnemonic in segment(isa, data[start:end]):
                off += start
                cands = D.candidates(b)
                pref = ([f for f in cands if T['forms'][f][0] == mnemonic] +
                        [f for f in cands if T['forms'][f][0] != mnemonic])
                res = D.decode(b, pref)
                if res is None:
                    sys.exit('%s+0x%x: %s (%s) does not round-trip' %
                             (fn, off, b.hex(), mnemonic))
                form, fields = res
                decoded += 1
                mn, ep = T['forms'][form][:2]
                key = (mn, ep, b.hex(),
                       tuple((i, v) for i, v in enumerate(fields) if v))
                seen.setdefault(key, (fn, off))

    cases = sorted(seen.items(), key=lambda kv: kv[0])
    out = []
    w = out.append
    w('/*')
    w(' * Copyright 2026 Aurora Silicon')
    w(' * SPDX-License-Identifier: MIT')
    w(' *')
    w(' * GENERATED by gen_agx3d_compose_corpus_vectors.py -- do not edit.')
    w(' * Real G18G (agx3d) instructions from the %d applegpu_g18g witness'
      % len(texts))
    w(' * texts in test/native/g18g, each decomposed into its field vector by')
    w(' * the table-driven decoder over agx3d_tables.c. Every vector names the')
    w(' * committed text and byte offset its bytes were read from. Duplicate')
    w(' * (form, bytes, fields) triples are kept once: %d distinct of %d'
      % (len(cases), decoded))
    w(' * decoded. This is a round trip through one table; see the generator')
    w(' * for what it does and does not prove.')
    w(' */')
    w('#include <stddef.h>')
    w('#include <stdint.h>')
    w('')
    w('struct agx3d_compose_corpus_case {')
    w('   const char *mnemonic;')
    w('   uint8_t ep;')
    w('   uint8_t nfields;')
    w('   const uint16_t *field_ids;')
    w('   const uint64_t *field_vals;')
    w('   uint8_t nbytes;')
    w('   const uint8_t *bytes;')
    w('   const char *text;')
    w('   uint32_t offset;')
    w('};')
    w('')
    for i, ((mn, ep, hx, fields), _) in enumerate(cases):
        ids = ','.join(str(k) for k, _ in fields) or '0'
        vals = ','.join('%dull' % v for _, v in fields) or '0'
        w('static const uint16_t agx3d_fid%d[] = {%s};' % (i, ids))
        w('static const uint64_t agx3d_fv%d[] = {%s};' % (i, vals))
        w('static const uint8_t agx3d_by%d[] = {%s};' %
          (i, ','.join('0x%02x' % x for x in bytes.fromhex(hx))))
    w('')
    w('static const struct agx3d_compose_corpus_case '
      'agx3d_compose_corpus_cases[] = {')
    for i, ((mn, ep, hx, fields), (fn, off)) in enumerate(cases):
        w('   {"%s", %d, %d, agx3d_fid%d, agx3d_fv%d, %d, agx3d_by%d, "%s", '
          '0x%x},' % (mn, ep, len(fields), i, i, len(hx) // 2, i, fn, off))
    w('};')
    w('')
    w('static const size_t agx3d_compose_corpus_case_count =')
    w('   sizeof(agx3d_compose_corpus_cases) / '
      'sizeof(agx3d_compose_corpus_cases[0]);')

    with open(sys.argv[1], 'w') as f:
        f.write('\n'.join(out) + '\n')

    sizes = collections.Counter(len(k[2]) // 2 for k in seen)
    print('texts %d, decoded %d, cases %d, forms %d, sizes %s' %
          (len(texts), decoded, len(cases), len({k[:2] for k in seen}),
           sorted(sizes.items())))


if __name__ == '__main__':
    main()
